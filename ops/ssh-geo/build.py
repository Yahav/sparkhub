#!/usr/bin/env python3
"""Build the ssh_geo nftables table from a RIPE NCC delegated-extended stats file.

SSH (tcp/22) is accepted from one registry country (COUNTRY), the LAN, Tailscale and loopback,
and from connections already established; everything else on port 22 is dropped. COUNTRY and TRUSTED4 come from
/etc/default/sparkhub-ssh-geo, which ./install.sh writes (the RIPE file covers Europe, the Middle East and
Central Asia only).
The table is replaced atomically and touches no other table (Docker, Tailscale keep theirs).
Usage: build.py <delegated-ripencc-extended-latest> > ssh-geo.nft
"""
import ipaddress
import os
import sys

COUNTRY = os.environ.get("COUNTRY", "")
TRUSTED4 = os.environ.get("TRUSTED4", "").split()  # LAN, Tailscale
if not COUNTRY or not TRUSTED4:
    # no built-in defaults: a wrong country or LAN locks SSH out (the caller then keeps the last good list)
    sys.exit("COUNTRY and TRUSTED4 must be set (in /etc/default/sparkhub-ssh-geo, written by ./install.sh)")
# sanity floor against a truncated download (a mid-sized country has hundreds of IPv4 blocks; set MIN_V4 to match)
MIN_V4 = int(os.environ.get("MIN_V4", "20"))

v4, v6 = [], []
for line in open(sys.argv[1]):
    p = line.strip().split("|")
    if len(p) < 7 or p[1] != COUNTRY or p[6] not in ("allocated", "assigned"):
        continue
    if p[2] == "ipv4":
        first = ipaddress.IPv4Address(p[3])
        v4 += ipaddress.summarize_address_range(first, first + int(p[4]) - 1)
    elif p[2] == "ipv6":
        v6.append(ipaddress.IPv6Network(f"{p[3]}/{p[4]}"))
v4 = list(ipaddress.collapse_addresses(v4))
v6 = list(ipaddress.collapse_addresses(v6))
if len(v4) < MIN_V4:
    sys.exit(f"only {len(v4)} {COUNTRY} IPv4 ranges (< {MIN_V4}); refusing to build a list that may lock people out")

def elems(nets):
    return ",\n      ".join(str(n) for n in nets)

print(f"""# Generated by build.py from the RIPE NCC registry: {len(v4)} IPv4 / {len(v6)} IPv6 {COUNTRY} ranges.
table inet ssh_geo
delete table inet ssh_geo
table inet ssh_geo {{
  set il4 {{
    type ipv4_addr; flags interval;
    elements = {{
      {elems(v4)}
    }}
  }}
  set il6 {{
    type ipv6_addr; flags interval;
    elements = {{
      {elems(v6)}
    }}
  }}
  chain input {{
    type filter hook input priority filter; policy accept;
    tcp dport 22 ct state established,related accept
    tcp dport 22 iifname {{ "lo", "tailscale0" }} accept
    tcp dport 22 ip saddr {{ {", ".join(TRUSTED4)} }} accept
    tcp dport 22 ip saddr @il4 accept
    tcp dport 22 ip6 saddr @il6 accept
    tcp dport 22 ip6 saddr fe80::/10 accept
    tcp dport 22 counter drop comment "ssh from outside {COUNTRY}"
  }}
}}""")
